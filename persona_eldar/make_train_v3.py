# вопросы, на которые уместен длинный ответ-поток через все его темы
STREAM_Q = [
    "мысли вслух",
    "что у тебя нового?",
    "расскажи, что у тебя на уме",
    "напиши пост в свой канал",
    "о чём сейчас думаешь?",
    "поток сознания давай",
    "расскажи про свою жизнь",
]

N_STREAM = 220       # сколько составить потоковых примеров
FRAGS_PER_STREAM = 9  # тем в одном ответе


def build_fragment_bank(texts_with_topics, rng):
    """Банк фрагментов (1-3 строки, 30-200 символов) из подлинных постов, по темам."""
    bank = {}
    for text, topic in texts_with_topics:
        lines = [l.strip() for l in text.split("\n") if l.strip()]
        if len(lines) < 1:
            continue
        for _ in range(2):  # до двух фрагментов с текста
            start = rng.randrange(len(lines))
            frag_lines = []
            for l in lines[start:start + rng.choice((1, 2, 2, 3))]:
                frag_lines.append(l)
            frag = "\n".join(frag_lines)
            if 30 <= len(frag) <= 200 and not URLish(frag):
                bank.setdefault(topic, []).append(frag)
    return bank


def URLish(s):
    import re as _re
    return bool(_re.search(r"https?://|www\.|@", s))


def build_stream(bank, rng):
    """Один ответ-поток: фрагменты из FRAGS_PER_STREAM разных тем."""
    topics = [t for t in bank if bank[t]]
    if len(topics) < FRAGS_PER_STREAM:
        return None
    chosen = rng.sample(topics, FRAGS_PER_STREAM)
    parts = [rng.choice(bank[t]) for t in chosen]
    return "\n".join(parts)


def main():
    rng = random.Random(42)

    def read(name):
        with open(os.path.join(DATA, name), encoding="utf-8") as f:
            return [json.loads(line) for line in f]

    train_v1, val_v1 = read("eldar_train.jsonl"), read("eldar_val.jsonl")

    def sample(question, answer, topic, tag):
        return {
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT_V3},
                {"role": "user", "content": question},
                {"role": "assistant", "content": answer},
            ],
            "meta": {"source_id": None, "date": None, "category": tag, "topic": topic},
        }

    rows = []
    texts_with_topics = []

    # 1. монологи с переложенными вопросами: 2 формулировки на текст
    for r in train_v1 + val_v1:
        answer = r["messages"][2]["content"]
        q_pair = make_questions(answer, rng)
        texts_with_topics.append((answer, q_pair[0][0]))
        for topic, q in q_pair:
            s = sample(q, answer, topic, "monologue_v3")
            s["meta"]["source_id"] = r.get("meta", {}).get("source_id")
            s["meta"]["date"] = r.get("meta", {}).get("date")
            rows.append(s)

    n_monologue = len(rows)

    # 2. фактовые QA: каждая пара x2 формулировки вопроса
    for questions, answer in FACT_QA:
        for q in questions[:2]:
            rows.append(sample(q, eldar_casing(answer), "факт", "fact_qa"))

    n_fact = len(rows) - n_monologue

    # 3. якоря v2 (идентичность + короткая беседа) x2
    anchors = []
    for questions, answers in IDENTITY:
        for i, q in enumerate(questions):
            anchors.append(sample(q, eldar_casing(answers[i % len(answers)]), "идентичность", "anchor_identity"))
    for q, answers in SHORT_TALK:
        for a in answers:
            anchors.append(sample(q, eldar_casing(a), "короткий ответ", "anchor_short"))
    rows += anchors * ANCHOR_REPEAT

    # 4. потоковые ответы: склейки фрагментов из FRAGS_PER_STREAM разных тем
    # подлинных постов — учат длинный ответ, прыгающий между темами
    bank = build_fragment_bank(texts_with_topics, rng)
    n_stream = 0
    for i in range(N_STREAM):
        stream = build_stream(bank, rng)
        if not stream:
            continue
        rows.append(sample(STREAM_Q[i % len(STREAM_Q)], stream, "поток", "stream"))
        n_stream += 1

    rng.shuffle(rows)

    # val: 37 монологов v1 с одним переложенным вопросом + 3 фактовых
    val_rows = []
    for r in val_v1:
        answer = r["messages"][2]["content"]
        topic, q = make_questions(answer, rng)[0]
        val_rows.append(sample(q, answer, topic, "monologue_v3"))
    val_rows += [sample(q, FACT_QA[i][1], "факт", "fact_qa") for i, (qs, _) in enumerate(FACT_QA) for q in qs[:1]][:3]

    def dump(name, out_rows):
        with open(os.path.join(DATA, name), "w", encoding="utf-8") as f:
            for r in out_rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")

    dump("eldar_train_v3.jsonl", rows)
    dump("eldar_val_v3.jsonl", val_rows)
    with open(os.path.join(DATA, "system_prompt.txt"), "w", encoding="utf-8") as f:
        f.write(SYSTEM_PROMPT_V3)

    from collections import Counter
    print(f"v3 train: {len(rows)} = монологи с новыми вопросами {n_monologue} "
          f"(из {len(train_v1) + len(val_v1)} текстов x2 формулировки) + факты {n_fact} "
          f"+ якоря x{ANCHOR_REPEAT}: {len(anchors) * ANCHOR_REPEAT} + потоковые {n_stream}")
    print("val:", len(val_rows))
    print("темы монологов:", dict(Counter(r['meta']['topic'] for r in rows if r['meta']['category'] == 'monologue_v3').most_common()))


if __name__ == "__main__":
    main()
