TITLE_IN_TEXT = re.compile(r"[«\"]([^«»\"]{3,50})[»\"]")


def make_questions(text, rng):
    """Два разных вопроса, на которые монолог реально отвечает."""
    q1_rule, q1 = None, None
    best_hits = 1
    for name, rx, questions in QUESTION_RULES:
        hits = len(rx.findall(text))
        if hits >= best_hits:
            best_hits = hits
            q1_rule, q1 = name, rng.choice(questions)

    candidates = []
    for t in TITLE_IN_TEXT.findall(text):
        t = t.strip()
        # название, а не случайная цитата: рядом слова кино/фильм/ролик
        window = re.search(rf"(кино|фильм|ролик|сценк)[^.«\"]{{0,25}}[«\"]{re.escape(t)}[»\"]", text, re.I) or \
                 re.search(rf"[«\"]{re.escape(t)}[»\"][^.«\"]{{0,25}}(кино|фильм|ролик|сценк)", text, re.I)
        if window and not re.search(r"https?|www|@", t):
            candidates += [f"расскажи про кино «{t}»", f"что за фильм «{t}»?"]

    if q1 is None and not candidates:
        return [("мысли", rng.choice(GENERIC_Q)), ("мысли", rng.choice(GENERIC_Q))]

    if q1 is None:
        q1, q1_rule = candidates[0], "фильм"
    elif candidates and rng.random() < 0.5:
        candidates.insert(0, q1)
        q1, q1_rule = candidates[0], q1_rule + "+фильм"

    pool = [q for name, rx, qs in QUESTION_RULES for q in qs if name != q1_rule.split("+")[0]]
    second = rng.choice(candidates[1:] + pool + GENERIC_Q)
    if second == q1:
        second = rng.choice(GENERIC_Q)
    return [(q1_rule, q1), ("разное", second)]


