def main():
    random.seed(42)

    def read(name):
        with open(os.path.join(DATA, name), encoding="utf-8") as f:
            return [json.loads(line) for line in f]

    train, val = read("eldar_train.jsonl"), read("eldar_val.jsonl")

    # заменяем системный промпт во всех примерах на v2
    for rows in (train, val):
        for r in rows:
            r["messages"][0]["content"] = SYSTEM_PROMPT_V2

    anchors = []

    def add(question, answer, topic):
        anchors.append({
            "messages": [
                {"role": "system", "content": SYSTEM_PROMPT_V2},
                {"role": "user", "content": question},
                {"role": "assistant", "content": answer},
            ],
            "meta": {"source_id": None, "date": None, "category": "anchor_identity", "topic": topic},
        })

    # идентичность: каждый вариант вопроса x каждый вариант ответа (без перебора всех пар)
    for questions, answers in IDENTITY:
        for i, q in enumerate(questions):
            add(q, answers[i % len(answers)], "идентичность")
    # короткая беседа
    for q, answers in SHORT_TALK:
        for a in answers:
            add(q, a, "короткий ответ")

    random.shuffle(anchors)
    train_v2 = train + anchors
    random.shuffle(train_v2)

    def dump(name, rows):
        with open(os.path.join(DATA, name), "w", encoding="utf-8") as f:
            for r in rows:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")

    dump("eldar_train_v2.jsonl", train_v2)
    dump("eldar_val_v2.jsonl", val)
    with open(os.path.join(DATA, "system_prompt.txt"), "w", encoding="utf-8") as f:
        f.write(SYSTEM_PROMPT_V2)

    print(f"v2: train {len(train)} -> {len(train_v2)} (+{len(anchors)} якорей), val {len(val)}")
    topics = {}
    for a in anchors:
        topics[a["meta"]["topic"]] = topics.get(a["meta"]["topic"], 0) + 1
    print("якоря по типам:", topics)


if __name__ == "__main__":
    main()
