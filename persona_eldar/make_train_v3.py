ANCHOR_REPEAT = 2  # утяжеление коротких якорей (умеренное: ответы не должны стать слишком короткими)


def eldar_casing(s):
    """Регистр как в подлинных постах: 96% текстов и 95% строк начинаются
    с заглавной (замер по корпусу), внутри строки — как написал."""
    return "\n".join(
        (l[:1].upper() + l[1:]) if l and l[0].islower() and l[0].isalpha() else l
        for l in s.split("\n")
    )


